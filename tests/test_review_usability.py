from sovereign_workbench.review_batches import connect


def _run(capsys, *argv):
    assert main(list(argv)) == 0, capsys.readouterr().err
    return json.loads(capsys.readouterr().out)


@pytest.fixture
def archive(tmp_path, capsys):
    docs = tmp_path / "docs"
    docs.mkdir()
    (docs / "log.txt").write_text("Grevillea cuttings rooted under mist.\n", encoding="utf-8")
    (docs / "log-copy.txt").write_text("Grevillea cuttings rooted under mist.\n", encoding="utf-8")
    db = tmp_path / "archive.db"
    _run(capsys, "archive-intake-register", str(docs), "--state-db", str(db),
         "--purpose", "synthetic", "--include", ".txt")
    _run(capsys, "archive-batch-create", str(docs), "--state-db", str(db), "--include", ".txt")
    return docs, db


@pytest.fixture
def screen(archive):
    docs, db = archive
    server, token = make_server(db, "Synthetic Reviewer")
    threading.Thread(target=server.serve_forever, daemon=True).start()
    base = f"http://127.0.0.1:{server.server_port}"

    def call(method, path, body=None, auth=True):
        headers = {"Content-Type": "application/json"}
        if auth:
            headers["Authorization"] = f"Bearer {token}"
        request = urllib.request.Request(base + path, method=method, headers=headers,
                                         data=json.dumps(body).encode() if body else None)
        try:
            with urllib.request.urlopen(request) as response:
                return response.status, json.loads(response.read())
        except urllib.error.HTTPError as error:
            return error.code, json.loads(error.read())

    yield docs, db, call
    server.shutdown()
    server.server_close()


def _decisions(db):
    with connect(db) as database:
        return database.execute("SELECT COUNT(*) FROM archive_review_decisions").fetchone()[0]


def test_page_has_no_stock_note_and_labels_the_summary_as_generated():
    assert "Human reviewed the candidate summary" not in HTML
    assert "generated by the Workbench, not part of the document" in HTML
    assert "required, in your own words" in HTML


def test_next_item_uses_plain_language(screen):
    _, _, call = screen
    status, data = call("GET", "/api/next")
    item = data["item"]
    assert status == 200 and item["route_label"] == "Needs your review"
    assert "couldn't confidently categorise" in item["display_reasons"]
    assert "classifier abstained" not in item["display_reasons"]


def test_document_text_is_shown_only_while_verified(screen):
    docs, _, call = screen
    item = call("GET", "/api/next")[1]["item"]
    status, document = call("GET", f"/api/source?source_id={item['source_id']}")
    assert status == 200 and document["verified"] is True
    assert document["text"] == "Grevillea cuttings rooted under mist.\n"
    (docs / item["source_path"]).write_text("edited after import\n", encoding="utf-8")
    status, document = call("GET", f"/api/source?source_id={item['source_id']}")
    assert (status, document["verified"], document["text"]) == (200, False, None)
    assert document["status"] == "CHANGED_SINCE_INTAKE"
    assert "changed since it was imported" in document["status_message"]
    (docs / item["source_path"]).unlink()
    document = call("GET", f"/api/source?source_id={item['source_id']}")[1]
    assert (document["status"], document["text"]) == ("MISSING", None)


def test_document_text_requires_the_access_token_and_a_known_source(screen):
    _, _, call = screen
    item = call("GET", "/api/next")[1]["item"]
    assert call("GET", f"/api/source?source_id={item['source_id']}", auth=False)[0] == 401
    assert call("GET", "/api/source?source_id=unknown")[0] == 404
    assert call("GET", "/api/source")[0] == 400


def test_a_decision_needs_the_reviewers_own_note(screen):
    _, db, call = screen
    item = call("GET", "/api/next")[1]["item"]
    for note in ("", "   "):
        status, reply = call("POST", "/api/decision", {
            "source_id": item["source_id"], "decision": "APPROVE", "note": note,
            "research_question": ""})
        assert status == 400 and "review note in your own words" in reply["error"]
    assert _decisions(db) == 0
    status, reply = call("POST", "/api/decision", {
        "source_id": item["source_id"], "decision": "APPROVE",
        "note": "Matches the nursery log", "research_question": ""})
    assert (status, reply) == (200, {"recorded": True}) and _decisions(db) == 1


def test_controller_rejects_blank_note(archive):
    _, db = archive
    with connect(db) as database:
        controller = ReviewController(database, "Synthetic Reviewer")
        with pytest.raises(ValueError, match="review note in your own words"):
            controller.accept(controller.pending()[0], "APPROVE", note="  ")


def test_search_groups_identical_copies_and_labels_metadata(archive, capsys):
    _, db = archive
    found = _run(capsys, "archive-search", "grevillea", "--state-db", str(db))
    paths = sorted(hit["relative_path"] for hit in found["results"])
    assert paths == ["log-copy.txt", "log.txt"]  # both stay visible with their own identity
    for hit in found["results"]:
        [twin] = hit["identical_to"]
        assert twin["relative_path"] != hit["relative_path"]
        assert twin["intake_root"] == hit["intake_root"]
        assert hit["metadata_match_labels"] == ["Workbench-generated summary"]
