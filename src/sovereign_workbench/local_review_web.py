ROUTE_LABELS = {
    "MANUAL_REVIEW_REQUIRED": "Needs your review",
    "RECOVERY_REQUIRED": "Text could not be read - check the file",
    "SPOT_CHECK_ELIGIBLE": "Quality spot check",
}
REASON_LABELS = {
    "classifier abstained or selected the fallback module":
        "The Workbench couldn't confidently categorise this document",
    "classification confidence is below 0.75": "Low confidence in the suggested category",
    "summary is empty": "No summary could be produced",
    "maturity is unresolved": "Its status (draft, research, evidence, etc.) is unclear",
    "no deterministic review exception matched": "Nothing unusual was detected",
}
REASON_PREFIXES = {
    "high-risk privacy candidate: ": "May contain sensitive personal or financial details: ",
    "external disclosure remains blocked: ": "Contains possible contact details: ",
    "extraction_status=": "Text extraction problem: ",
}


def _plain_reason(reason: str) -> str:
    if reason in REASON_LABELS:
        return REASON_LABELS[reason]
    for prefix, label in REASON_PREFIXES.items():
        if reason.startswith(prefix):
            return label + reason[len(prefix):].replace("_", " ")
    return reason


def _display_reasons(value: str) -> str:
    try:
        decoded = json.loads(value)
    except json.JSONDecodeError:
        return _plain_reason(value)
    if isinstance(decoded, list):
        return "\n".join(f"• {_plain_reason(str(item))}" for item in decoded)
    return _plain_reason(str(decoded))


def make_server(state_db: Path, reviewer: str, token: str | None = None) -> tuple[HTTPServer, str]:
    access_token = token or secrets.token_urlsafe(32)
    database_path = state_db.resolve(strict=True)
    # Files the reviewer chose to skip in this session. Not a decision; never stored.
    skipped: set[str] = set()
    set_aside: dict[str, dict[str, str]] = {}  # this session only; nothing is recorded

    class Handler(BaseHTTPRequestHandler):
        def log_message(self, format: str, *args: object) -> None:
            return

        def _authorized(self) -> bool:
            supplied = self.headers.get("Authorization", "")
            return hmac.compare_digest(supplied, f"Bearer {access_token}")

        def _json(self, status: HTTPStatus, value: dict[str, object]) -> None:
            body = json.dumps(value).encode("utf-8")
            self.send_response(status)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            self.end_headers()
            self.wfile.write(body)

        def _controller(self) -> tuple[object, ReviewController]:
            database = connect(database_path)
            return database, ReviewController(database, reviewer)

        def _queue(self, *, check_next: bool = False) -> tuple[list, int]:
            """Pending items not skipped or set aside in this session, and how many were skipped.

            With check_next (only when choosing what to show next), a next file that no longer
            matches its import fingerprint is set aside for this session (listed on the page,
            nothing recorded) instead of blocking the queue. A file that changes while it is
            on screen stays current, so its decision is refused with the specific reason.
            """
            database, controller = self._controller()
            try:
                pending = controller.pending()
            finally:
                database.close()
            pending_ids = {item.source_id for item in pending}
            for source_id in list(set_aside):
                if source_id not in pending_ids:
                    del set_aside[source_id]
            available = []
            for item in pending:
                if item.source_id in skipped or item.source_id in set_aside:
                    continue
                if check_next and not available:
                    status, _ = _read_verified(item.root, item.source_path, item.source_sha256,
                                               SET_ASIDE_CHECK_BYTES)
                    if status != VERIFIED:
                        set_aside[item.source_id] = {
                            "source_path": item.source_path, "status": status,
                            "explanation": STATUS_MESSAGES[status]}
                        continue
                available.append(item)
            return available, sum(item.source_id in skipped for item in pending)

        def _busy(self) -> None:
            self._json(HTTPStatus.SERVICE_UNAVAILABLE,
                       {"error": "The review database is busy or unavailable (another Workbench "
                                 "command may be using it). Nothing was recorded; try again in a moment."})

        def do_GET(self) -> None:
            path = urlparse(self.path).path
            if path == "/":
                body = HTML.encode("utf-8")
                self.send_response(HTTPStatus.OK)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.send_header("Content-Length", str(len(body)))
                self.send_header("Cache-Control", "no-store")
                self.send_header("X-Content-Type-Options", "nosniff")
                self.send_header("Content-Security-Policy", "default-src 'self'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'self'; frame-ancestors 'none'")
                self.end_headers()
                self.wfile.write(body)
                return
            if path not in {"/api/next", "/api/source"}:
                self._json(HTTPStatus.NOT_FOUND, {"error": "Not found"})
                return
            if not self._authorized():
                self._json(HTTPStatus.UNAUTHORIZED, {"error": "Local review access was denied"})
                return
            try:
                if path == "/api/source":
                    self._source()
                    return
                available, skipped_count = self._queue(check_next=True)
            except sqlite3.Error:
                self._busy()
                return
            if not available:
                self._json(HTTPStatus.OK, {"item": None, "remaining": 0, "skipped": skipped_count,
                                           "set_aside": list(set_aside.values())})
                return
            item = available[0]
            value = asdict(item)
            value["display_reasons"] = _display_reasons(item.route_reasons)
            value["route_label"] = ROUTE_LABELS.get(item.review_route, item.review_route)
            value["research_question"] = propose_research_question(item)
            self._json(HTTPStatus.OK, {"item": value, "remaining": len(available),
                                       "skipped": skipped_count,
                                       "set_aside": list(set_aside.values())})

        def _source(self) -> None:
            source_ids = parse_qs(urlparse(self.path).query).get("source_id", [])
            if len(source_ids) != 1:
                self._json(HTTPStatus.BAD_REQUEST, {"error": "Exactly one source_id is required"})
                return
            available, _ = self._queue()
            # Only the document currently under review is served.
            if not available or available[0].source_id != source_ids[0]:
                self._json(HTTPStatus.CONFLICT,
                           {"error": "Only the document currently under review can be shown; reload the page"})
                return
            item = available[0]
            # Shown only if the bytes read now still match the intake hash.
            self._json(HTTPStatus.OK, read_verified_text(item.root, item.source_path, item.source_sha256))

        def _payload(self, required: set[str]) -> dict[str, str]:
            length = int(self.headers.get("Content-Length", "0"))
            if length <= 0 or length > MAX_REQUEST_BYTES:
                raise ValueError("The review request size is invalid")
            payload = json.loads(self.rfile.read(length))
            if not isinstance(payload, dict) or set(payload) != required:
                raise ValueError("The review request fields are invalid")
            if not all(isinstance(payload[key], str) for key in required):
                raise ValueError("The review request values must be text")
            return payload

        def _current(self, source_id: str):
            available, _ = self._queue()
            if not available or available[0].source_id != source_id:
                raise ValueError("The pending review item changed; reload before deciding")
            return available[0]

        def do_POST(self) -> None:
            path = urlparse(self.path).path
            if path not in {"/api/decision", "/api/skip", "/api/skipped/reset"}:
                self._json(HTTPStatus.NOT_FOUND, {"error": "Not found"})
                return
            if not self._authorized():
                self._json(HTTPStatus.UNAUTHORIZED, {"error": "Local review access was denied"})
                return
            try:
                if path == "/api/skip":
                    # Skipping records nothing; it only moves this session past the file.
                    skipped.add(self._current(self._payload({"source_id"})["source_id"]).source_id)
                    self._json(HTTPStatus.OK, {"skipped": True})
                    return
                if path == "/api/skipped/reset":
                    self._payload(set())
                    skipped.clear()
                    set_aside.clear()
                    self._json(HTTPStatus.OK, {"skipped": 0})
                    return
                payload = self._payload({"source_id", "decision", "note", "research_question"})
                decision = DECISIONS.get(payload["decision"])
                if decision is None:
                    raise ValueError("The selected review decision is invalid")
                if not payload["note"].strip():
                    raise ValueError("Write a short review note in your own words before choosing a decision")
                item = self._current(payload["source_id"])
                database, controller = self._controller()
                try:
                    question = payload["research_question"] if decision == "NEEDS_RESEARCH" else ""
                    inserted = controller.accept(item, decision, note=payload["note"], research_question=question)
                    if inserted != 1:
                        raise ValueError("This exact review decision was already recorded")
                finally:
                    database.close()
                self._json(HTTPStatus.OK, {"recorded": True})
            except sqlite3.Error:
                self._busy()
            except (OSError, ValueError, json.JSONDecodeError) as exc:
                self._json(HTTPStatus.BAD_REQUEST, {"error": str(exc)})

    return HTTPServer(("127.0.0.1", 0), Handler), access_token


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser(description="One-file-at-a-time local archive review")
    result.add_argument("--state-db", required=True, type=Path)
    result.add_argument("--reviewer", required=True)
    result.add_argument("--no-browser", action="store_true", help=argparse.SUPPRESS)
    return result


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    if not args.reviewer.strip():
        raise ValueError("A human reviewer name is required")
    server, token = make_server(args.state_db, args.reviewer)
    url = f"http://127.0.0.1:{server.server_port}/#{token}"
    print(f"Local review is ready at {url}")
    print("Keep this window open while reviewing. Press Ctrl+C here when finished.")
    if not args.no_browser:
        threading.Timer(0.2, webbrowser.open, args=(url,)).start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
